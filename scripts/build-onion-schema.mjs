import { readFile, writeFile } from 'node:fs/promises';
import Ajv from 'ajv';
import standalone from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
const schema = JSON.parse(await readFile(new URL('../formats/onion/schema.json', import.meta.url), 'utf8'));
const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true }, strict: true, strictRequired: false });
const code = standalone(ajv, ajv.compile(schema));
const result = await build({ stdin: { contents: code, resolveDir: process.cwd(), sourcefile: 'onion-schema.mjs' }, bundle: true, format: 'esm', platform: 'neutral', minify: true, write: false });
const output = '// Generated by npm run build:onion-schema. Do not edit.\n' + result.outputFiles[0].text;
const target = new URL('../formats/onion/schema-validator.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Schema validator is stale. Run npm run build:onion-schema.');
} else await writeFile(target, output);
